// Cyrillic player / team names.
//
// The game keeps the names in fixed buffers inside the exe image, already in its own text encoding
// (found from the "get surname/name/team name" functions, see notes below), and builds them from
// physical keys only, so a Ukrainian layout still yields Latin letters. Windows nevertheless sends the
// real characters as WM_CHAR. This class
//   * remembers what was typed (Latin from WM_KEYDOWN, Cyrillic from WM_CHAR, one segment per Enter);
//   * when a name buffer gets a new Latin value equal to a typed segment, writes the Cyrillic segment
//     instead, encoded with the mod's charset (namechars.tsv, generated by build_mod.py);
//   * optionally (Config.ConvertOldNames) converts Latin names from other translations' saves by the
//     Ukrainian keyboard layout (ieyhfy -> шунран).
//
// Buffers (RVA in the current Steam P5R.exe): surname 0x28654B6 [20], name 0x28654CA [20], team 0x28654DE [40].
// They are checked against the code that reads them before use.
using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.IO;
using System.Runtime.InteropServices;
using System.Text;
using System.Threading;

namespace P5RUkr
{
    public static unsafe class Names
    {
        // (RVA of "lea rcx, [rip + buffer]" in the getter, buffer RVA, buffer size)
        static readonly (long lea, long buf, int size, string what)[] Buffers =
        {
            (0xD64649, 0x28654B6, 0x14, "surname"),
            (0xD65449, 0x28654CA, 0x14, "name"),
            (0xD646C9, 0x28654DE, 0x28, "team"),
        };

        // Ukrainian keyboard layout over the US one (the game accepts letters and some punctuation keys)
        const string LatinKeys = "qwertyuiopasdfghjklzxcvbnm[];',.`\\";
        const string UkrainianKeys = "йцукенгшщзфівапролдячсмитьхїжєбю'ґ";
        // virtual-key codes of the punctuation keys above
        static readonly Dictionary<int, char> OemKeys = new()
            { [0xDB] = '[', [0xDD] = ']', [0xBA] = ';', [0xDE] = '\'', [0xBC] = ',', [0xBE] = '.', [0xC0] = '`', [0xDC] = '\\' };
        // placeholders the game keeps before a save is loaded, and the default English names: never converted
        static readonly HashSet<string> Defaults = new(StringComparer.OrdinalIgnoreCase)
            { "Protagonist", "Ren", "Amamiya", "Akira", "Kurusu", "The Phantoms", "Phantoms", "Joker" };

        static Config _cfg;
        static Dictionary<char, byte[]> _enc;
        static long _base;
        static readonly string[] _last = new string[3];
        // Latin word -> its Cyrillic form, for every name converted so far (the full-name buffer is built from them)
        static readonly Dictionary<string, string> Known = new(StringComparer.OrdinalIgnoreCase);
        static readonly HashSet<string> Logged = new();

        // typed segments: Latin (from virtual keys) and the characters Windows actually produced
        static readonly List<(StringBuilder lat, StringBuilder chr)> Typed = new() { (new(), new()) };
        static readonly object Lock = new();

        public static void Start(Config cfg, string modDir)
        {
            _cfg = cfg;
            _enc = LoadCharset(Path.Combine(modDir, "namechars.tsv"));
            if (_enc.Count == 0) { Mod.Log("names: namechars.tsv missing"); return; }
            _base = (long)Process.GetCurrentProcess().MainModule.BaseAddress;
            foreach (var b in Buffers)
            {
                byte* p = (byte*)(_base + b.lea);
                if (p[0] != 0x48 || p[1] != 0x8D || p[2] != 0x0D || b.lea + 7 + *(int*)(p + 3) != b.buf)
                {
                    Mod.Log($"names: unexpected code at +{b.lea:X} (different game version?), name support disabled");
                    return;
                }
            }
            Mod.Log("names: buffers verified");
            Window.OnMessage += OnMessage;
            if (cfg.UkrainianNameInput)
            {
                Window.CharFilter = ToLatinKey;
                // Entry.Start(modDir);  // live Cyrillic in the entry field: disabled — the field has several copies,
                //                          the memory search can hit the wrong one (see Entry.cs); needs the code path

            }
            new Thread(Poll) { IsBackground = true }.Start();
        }

        static Dictionary<char, byte[]> LoadCharset(string path)
        {
            var d = new Dictionary<char, byte[]>();
            if (!File.Exists(path)) return d;
            foreach (var line in File.ReadAllLines(path, Encoding.UTF8))
            {
                var t = line.Split('\t');
                if (t.Length == 2 && t[0].Length == 1) d[t[0][0]] = Convert.FromHexString(t[1]);
            }
            return d;
        }

        // Cyrillic character -> the Latin character of the same key (Ukrainian layout; Russian-only letters too)
        static char ToLatinKey(char c)
        {
            char lc = char.ToLower(c);
            int k = UkrainianKeys.IndexOf(lc);
            char lat = k >= 0 ? LatinKeys[k] : lc switch { 'ы' => 's', 'э' => '\'', 'ъ' => ']', 'ё' => '`', _ => '\0' };
            if (lat == '\0' || c == '\'') return c;
            return char.IsUpper(c) ? char.ToUpper(lat) : lat;
        }

        // the entry being typed now: (Latin from the keys, characters Windows produced)
        public static (string, string) CurrentSegment()
        {
            lock (Lock) { var (l, c) = Typed[^1]; return (l.ToString(), c.ToString()); }
        }

        // ---------- keyboard ----------
        const uint WM_KEYDOWN = 0x100, WM_CHAR = 0x102;

        static void OnMessage(uint msg, IntPtr w)
        {
            if (!_cfg.UkrainianNameInput) return;
            lock (Lock)
            {
                var (lat, chr) = Typed[^1];
                if (msg == WM_KEYDOWN)
                {
                    int vk = (int)w;
                    if (vk == 0x0D) { if (lat.Length > 0) Typed.Add((new(), new())); }
                    else if (vk == 0x08) { if (lat.Length > 0) lat.Length--; if (chr.Length > 0) chr.Length--; }
                    else if (vk >= 0x41 && vk <= 0x5A) lat.Append((char)(vk + 32));
                    else if (OemKeys.TryGetValue(vk, out var oc)) lat.Append(oc);
                    else if (vk >= 0x30 && vk <= 0x39 || vk == 0x20) lat.Append((char)vk);
                    if (Typed.Count > 16) Typed.RemoveAt(0);
                }
                else if (msg == WM_CHAR)
                {
                    char c = (char)(int)w;
                    if (char.IsLetterOrDigit(c) || c == ' ' || c == '\'') chr.Append(c);
                    Entry.Touch();
                }
            }
        }

        // ---------- name buffers ----------
        static void Poll()
        {
            while (true)
            {
                Thread.Sleep(300);
                try
                {
                    for (int i = 0; i < Buffers.Length; i++) Check(i);
                }
                catch (Exception e) { Mod.Log("names: " + e.Message); Thread.Sleep(5000); }
            }
        }

        static void Check(int i)
        {
            var b = Buffers[i];
            byte* p = (byte*)(_base + b.buf);
            var cur = DecodeLatin(p, b.size);
            if (cur == _last[i]) return;
            _last[i] = cur;
            if (string.IsNullOrEmpty(cur)) return;
            if (Logged.Add("=" + b.what + cur)) Mod.Log($"names: {b.what} = '{cur}'");

            string uk = null;
            if (_cfg.UkrainianNameInput) uk = FromTyped(cur);
            if (uk == null) uk = FromKnown(cur);
            if (uk == null && _cfg.ConvertOldNames && IsLetters(cur) && !Defaults.Contains(cur)) uk = ByLayout(cur);
            if (uk == null || uk == cur) return;
            uk = Capitalize(uk);
            if (Write(p, b.size, uk))
            {
                _last[i] = null;
                if (!cur.Contains(' ')) Known[cur] = uk;
                // the confirm screen copies the entry into the buffers every frame: log each conversion once
                if (Logged.Add(b.what + cur)) Mod.Log($"names: {b.what} '{cur}' -> '{uk}'");
            }
        }

        // "Nfhfc Itdxtyrj" -> "Тарас Шевченко" when every word was converted before
        static string FromKnown(string cur)
        {
            // words typed in English stay as they are ("Ren Itdxtyrj" -> "Ren Шевченко")
            var words = cur.Split(' ');
            if (words.Length < 2) return null;
            bool any = false;
            for (int k = 0; k < words.Length; k++)
                if (Known.TryGetValue(words[k], out var w)) { words[k] = w; any = true; }
            return any ? string.Join(" ", words) : null;
        }

        // The game stores names in its own encoding: plain ASCII bytes or 2-byte codes 0x80 xx where
        // xx - 0x60 is the character (the first 128 glyphs are ASCII). Returns null when the name holds
        // anything else (e.g. it is already Cyrillic).
        static string DecodeLatin(byte* p, int size)
        {
            var sb = new StringBuilder();
            for (int k = 0; k < size && p[k] != 0; k++)
            {
                if (p[k] < 0x80) { sb.Append((char)p[k]); continue; }
                if (p[k] != 0x80 || k + 1 >= size) return null;
                int idx = p[++k] - 0x60;
                if (idx < 0x20 || idx > 0x7E) return null;
                sb.Append((char)idx);
            }
            return sb.ToString();
        }

        // names start with a capital letter: "віталій єрмо" -> "Віталій Єрмо"
        static string Capitalize(string s)
        {
            var c = s.ToCharArray();
            for (int k = 0; k < c.Length; k++)
                if (k == 0 || c[k - 1] == ' ') c[k] = char.ToUpper(c[k]);
            return new string(c);
        }

        static bool IsLetters(string s)
        {
            foreach (var c in s)
                if (!(c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c == ' ' || LatinKeys.IndexOf(c) >= 26)) return false;
            return true;
        }

        // the Cyrillic text typed for this Latin value (case taken from the game's value)
        static string FromTyped(string cur)
        {
            lock (Lock)
            {
                for (int s = Typed.Count - 1; s >= 0; s--)
                {
                    var (lat, chr) = Typed[s];
                    if (lat.Length != cur.Length || chr.Length != cur.Length) continue;
                    if (!string.Equals(lat.ToString(), cur, StringComparison.OrdinalIgnoreCase)) continue;
                    var c = chr.ToString();
                    bool cyr = false;
                    foreach (var ch in c) if (ch >= 'Ѐ' && ch <= 'ӿ') cyr = true;
                    if (!cyr) return null;
                    var sb = new StringBuilder();
                    for (int k = 0; k < c.Length; k++)
                        sb.Append(char.IsUpper(cur[k]) ? char.ToUpper(c[k]) : char.ToLower(c[k]));
                    return sb.ToString();
                }
            }
            return null;
        }

        static string ByLayout(string cur)
        {
            var sb = new StringBuilder();
            foreach (var c in cur)
            {
                int k = LatinKeys.IndexOf(char.ToLower(c));
                char u = k < 0 ? c : UkrainianKeys[k];
                sb.Append(char.IsUpper(c) ? char.ToUpper(u) : u);
            }
            return sb.ToString();
        }

        static bool Write(byte* p, int size, string s)
        {
            var bytes = new List<byte>();
            foreach (var c in s)
            {
                if (_enc.TryGetValue(c, out var e)) bytes.AddRange(e);
                else if (c < 0x80) bytes.Add((byte)c);
                else return false;
            }
            if (bytes.Count >= size) { Mod.Log($"names: '{s}' too long for the buffer ({bytes.Count}/{size - 1} bytes)"); return false; }
            for (int k = 0; k < size; k++) p[k] = k < bytes.Count ? bytes[k] : (byte)0;
            return true;
        }
    }
}
